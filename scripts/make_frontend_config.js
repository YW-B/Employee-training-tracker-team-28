// EN: Writes frontend/config.local.js from the Cognito ids that infra/floci/cognito/cognito_init.js produced.
//     The web client id is a public value (the browser needs it to sign in); it is not a secret.
//     frontend/config.local.js is git-ignored because it changes every time Cognito is set up again.
//     Run from the repo root, after cognito_init.js:   node scripts/make_frontend_config.js
// Franco: Beykteb frontend/config.local.js men el Cognito ids elly cognito_init.js 3amalha.
//     El web client id 2eema public (el browser me7tagha lel login); mesh secret.
//     frontend/config.local.js git-ignored 3ashan beyetghayyar kol mara Cognito yet3emel men el awel.
//     Shaghalo men awel el repo, ba3d cognito_init.js:   node scripts/make_frontend_config.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'infra', 'floci', 'cognito', 'cognito.generated.env');
const target = path.join(root, 'frontend', 'config.local.js');

if (!fs.existsSync(source)) {
  console.error('Missing infra/floci/cognito/cognito.generated.env: run "node infra/floci/cognito/cognito_init.js" first.');
  process.exit(1);
}

// EN: read KEY=value lines; keep only the public web client id.
// Franco: ne2ra sotoor KEY=value; nakhod el web client id el public bas.
const env = Object.fromEntries(fs.readFileSync(source, 'utf8').split(/\r?\n/)
  .filter((line) => /^[A-Z0-9_]+=/.test(line))
  .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1).trim()]));
const clientId = env.COGNITO_WEB_CLIENT_ID || '';
if (!/^[A-Za-z0-9_-]+$/.test(clientId)) {
  console.error('COGNITO_WEB_CLIENT_ID is missing or has unexpected characters in cognito.generated.env.');
  process.exit(1);
}

fs.writeFileSync(target, [
  '// EN: generated by scripts/make_frontend_config.js - do not edit, do not commit.',
  '// Franco: ma3mool b scripts/make_frontend_config.js - mate3addelsh w matkommitsh.',
  `window.ETT_CONFIG = Object.assign(window.ETT_CONFIG || {}, { cognitoClientId: ${JSON.stringify(clientId)} });`,
  '',
].join('\n'));
console.log('Wrote frontend/config.local.js');
