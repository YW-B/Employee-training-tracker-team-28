// EN: Reads the security events back from CloudWatch Logs: every auth_failure (401) and forbidden (403)
//     line of the last N minutes (default 60) in /ett/s1, /ett/s2 and /ett/s3, counted per service, per path
//     and per minute. It also shows the alarm state. The output is what the report's logging evidence uses,
//     and it is saved to docs/evidence/logging/security_log_queries.md.
//     Run from the repo root:   node scripts/security_log_queries.js [minutes]
// Franco: Beye2ra el security events men CloudWatch Logs: kol satr auth_failure (401) w forbidden (403) fe
//     akher N de2ee2a (el default 60) fe /ett/s1 w /ett/s2 w /ett/s3, ma3dooda le kol service w path w de2ee2a.
//     W beywarry 7alet el alarm. El output da evidence el logging fel report, w beyetsayyev fe
//     docs/evidence/logging/security_log_queries.md.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { callAws, callAwsQuery } = require('../services/common/aws');
const { hostAwsConfig, LOG_GROUPS } = require('./aws_host_config');

async function main() {
  const minutes = Number(process.argv[2] || 60);
  const config = hostAwsConfig();
  const since = Date.now() - minutes * 60 * 1000;
  const events = [];
  const problems = [];
  for (const group of LOG_GROUPS) {
    let nextToken;
    try {
      do {
        const page = await callAws('logs', 'Logs_20140328.FilterLogEvents', {
          logGroupName: group, startTime: since, filterPattern: '{ ($.event = "auth_failure") || ($.event = "forbidden") }', nextToken,
        }, { config });
        for (const e of page.events || []) {
          try { events.push({ group, ...JSON.parse(e.message) }); } catch { /* not a JSON line */ }
        }
        nextToken = page.nextToken;
      } while (nextToken);
    } catch (err) {
      problems.push(`${group}: ${err.message}`);
    }
  }
  // EN: some emulators ignore the filter pattern, so we filter again here to be sure.
  // Franco: ba3d el emulators bey-tnatto el filter pattern, f benfilter tany hena 3ashan net2akked.
  const security = events.filter((e) => e.event === 'auth_failure' || e.event === 'forbidden');
  const count = (keyOf) => security.reduce((m, e) => { const k = keyOf(e); m[k] = (m[k] || 0) + 1; return m; }, {});
  const table = (title, obj) => [`### ${title}`, '', '| Key | Count |', '|---|---|',
    ...Object.entries(obj).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`), ''];

  let alarm = 'unknown';
  try {
    const xml = await callAwsQuery('monitoring', 'DescribeAlarms', { 'AlarmNames.member.1': 'ett-repeated-auth-failures' }, { config });
    alarm = (xml.match(/<StateValue>([^<]+)<\/StateValue>/) || [])[1] || 'not found';
  } catch (err) {
    problems.push(`alarm: ${err.message}`);
  }

  const lines = [
    '# Security events in CloudWatch Logs',
    '',
    `Generated by \`node scripts/security_log_queries.js ${minutes}\` on ${new Date().toISOString()}: the last ${minutes} minutes of ${LOG_GROUPS.join(', ')}.`,
    '',
    `**Total:** ${security.length} security events (${security.filter((e) => e.event === 'auth_failure').length} auth_failure = 401, ${security.filter((e) => e.event === 'forbidden').length} forbidden = 403). Alarm \`ett-repeated-auth-failures\`: **${alarm}**.`,
    '',
    ...table('Per service', count((e) => `${e.group} (${e.event})`)),
    ...table('Per path', count((e) => `${e.method || ''} ${e.path || ''} -> ${e.status}`)),
    ...table('Per minute (UTC)', count((e) => String(e.timestamp || '').slice(0, 16))),
    'No token, password or Authorization header appears in these lines: they are redacted before they are written (services/common/logging.js).',
  ];
  if (problems.length) lines.push('', '**Problems while reading:**', '', ...problems.map((p) => `- ${p}`));
  const out = path.join(__dirname, '..', 'docs', 'evidence', 'logging');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'security_log_queries.md'), `${lines.join('\n')}\n`);
  console.log(lines.join('\n'));
  process.exit(problems.length && !security.length ? 1 : 0);
}

main();
