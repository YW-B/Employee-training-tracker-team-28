// EN: Runs the end-to-end Newman collection (tests/newman) against the running stack through nginx (HTTPS)
//     and saves the evidence in docs/evidence/newman/: the full JSON report and a short summary.md table.
//     The Cognito client id and the test password are read from your local, git-ignored files and passed
//     to Newman on the command line, so they are never written into the collection.
//     Run from the repo root (stack up, seed + Cognito users loaded):   node scripts/run_newman.js
// Franco: Beyshaghal collection Newman el end-to-end (tests/newman) 3ala el stack el shaghal 3an taree2 nginx
//     (HTTPS) w beysayyev el evidence fe docs/evidence/newman/: el report JSON kamel w gadwal summary.md.
//     El Cognito client id w password el test bey-et2eru men el files el local (git-ignored) w beyetba3to
//     le Newman fel command line, f 3omrohom ma beyetketbo fel collection.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { loadSettings } = require('../tests/security/lib');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'docs', 'evidence', 'newman');
const REPORT = path.join(OUT, 'newman-report.json');
const CA = path.join(ROOT, 'certs', 'server.crt');

const s = loadSettings();
if (!s.clientId || !s.password) {
  console.error('Missing COGNITO_WEB_CLIENT_ID or TEST_USER_PASSWORD (run cognito_init.js; check .env).');
  process.exit(2);
}
fs.mkdirSync(OUT, { recursive: true });

// EN: newman comes from npm (npx downloads it once). TLS stays on: we trust our own self-signed certificate.
// Franco: newman gai men npm (npx beyenazzelo mara). El TLS shaghal: benseddaa2 el certificate bta3na.
const args = ['--yes', 'newman@6', 'run', path.join('tests', 'newman', 'e2e.postman_collection.json'),
  '-e', path.join('tests', 'newman', 'local.postman_environment.json'),
  '--env-var', `baseUrl=${s.baseUrl}`, '--env-var', `clientId=${s.clientId}`, '--env-var', `password=${s.password}`,
  '--working-dir', path.join('tests', 'newman'),
  '--reporters', 'cli,json', '--reporter-json-export', REPORT];
if (fs.existsSync(CA)) args.push('--ssl-extra-ca-certs', CA);

const run = spawnSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', args, { cwd: ROOT, stdio: 'inherit', shell: process.platform === 'win32' });
if (!fs.existsSync(REPORT)) {
  console.error('Newman did not produce a report.');
  process.exit(run.status || 1);
}

// EN: turn the JSON report into a readable table (one row per request, with its assertions).
//     Tokens never appear: Newman's JSON report is reduced to names, status codes and pass/fail.
// Franco: n7awwel el report JSON le gadwal (satr le kol request, ma3 el assertions bta3to).
//     El tokens 3omraha ma betetla3: bnakhod mn el report el asamy w el status w pass/fail bas.
const report = JSON.parse(fs.readFileSync(REPORT, 'utf8'));
const rows = report.run.executions.map((e) => {
  const asserts = e.assertions || [];
  const failed = asserts.filter((a) => a.error);
  return `| ${e.item.name} | ${e.response ? e.response.code : 'no answer'} | ${asserts.length - failed.length}/${asserts.length} | ${failed.length ? `**FAIL**: ${failed.map((a) => a.assertion).join('; ')}` : 'PASS'} |`;
});
const st = report.run.stats.assertions;
fs.writeFileSync(path.join(OUT, 'summary.md'), [
  '# Newman end-to-end results',
  '',
  `Generated by \`node scripts/run_newman.js\` on ${new Date().toISOString()} against ${s.baseUrl} (nginx, HTTPS). Full report: \`newman-report.json\`.`,
  '',
  `**Assertions:** ${st.total - st.failed} passed, ${st.failed} failed, ${st.total} total.`,
  '',
  '| Request | HTTP status | Assertions passed | Result |',
  '|---|---|---|---|',
  ...rows,
  '',
].join('\n'));

// EN: the JSON report keeps request headers, so we remove the Authorization values before it is kept.
// Franco: el report JSON beyekhazzen el headers, f bnemsa7 2eyam el Authorization abl ma netrkoh.
const text = fs.readFileSync(REPORT, 'utf8')
  .replace(/eyJ[A-Za-z0-9_-]{5,}\.[A-Za-z0-9_-]{5,}\.[A-Za-z0-9_-]*/g, '[REDACTED_JWT]')
  .replace(new RegExp(s.password.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g'), '[REDACTED]');
fs.writeFileSync(REPORT, text);

console.log(`\nSummary: docs/evidence/newman/summary.md (${st.total - st.failed}/${st.total} assertions passed)`);
process.exit(st.failed ? 1 : 0);
